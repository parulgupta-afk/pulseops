// Load test for POST /api/incidents — the endpoint the spec's non-functional
// requirement targets directly: "handle 500 concurrent incident triggers
// with p95 latency under 200ms."
//
// Requires the k6 binary (https://k6.io/docs/get-started/installation/) —
// it's not an npm package, so `npm install` won't fetch it.
//
// Usage:
//   PULSEOPS_EMAIL=you@example.com PULSEOPS_PASSWORD=yourpassword \
//     k6 run k6/incident-ingestion.js
//
// Override the target or ramp shape:
//   BASE_URL=http://localhost:4000 k6 run k6/incident-ingestion.js

import http from "k6/http";
import { check, sleep } from "k6";

const BASE_URL = __ENV.BASE_URL || "http://localhost:4000";

export const options = {
  scenarios: {
    ramping: {
      executor: "ramping-vus",
      startVUs: 0,
      stages: [
        { duration: "30s", target: 50 },
        { duration: "1m", target: 500 }, // sustained load matching the spec's target concurrency
        { duration: "30s", target: 0 },
      ],
    },
  },
  thresholds: {
    // This is the actual pass/fail bar from the spec — k6 exits non-zero if
    // it's not met, so this can be wired into CI as a real regression gate,
    // not just a number to eyeball after the run.
    "http_req_duration{endpoint:create_incident}": ["p(95)<200"],
    http_req_failed: ["rate<0.01"],
  },
};

// Runs once, regardless of VU count, and its return value is handed to every
// VU's default() call — so we log in exactly once instead of once per VU.
export function setup() {
  const email = __ENV.PULSEOPS_EMAIL;
  const password = __ENV.PULSEOPS_PASSWORD;
  if (!email || !password) {
    throw new Error(
      "Set PULSEOPS_EMAIL and PULSEOPS_PASSWORD env vars (an existing account — register one via the UI first)."
    );
  }

  const loginRes = http.post(
    `${BASE_URL}/api/auth/login`,
    JSON.stringify({ email, password }),
    { headers: { "Content-Type": "application/json" } }
  );

  if (loginRes.status !== 200) {
    throw new Error(`Login failed during setup (status ${loginRes.status}): ${loginRes.body}`);
  }

  return { token: loginRes.json("token") };
}

export default function (data) {
  const idempotencyKey = `k6-${__VU}-${__ITER}-${Date.now()}`;

  const res = http.post(
    `${BASE_URL}/api/incidents`,
    JSON.stringify({
      idempotencyKey,
      title: "Load test incident",
      description: "Generated by the k6 incident-ingestion load test",
    }),
    {
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${data.token}` },
      tags: { endpoint: "create_incident" }, // lets the threshold above target just this request type
    }
  );

  check(res, {
    "status is 200 or 201": (r) => r.status === 200 || r.status === 201,
  });

  sleep(0.1);
}
